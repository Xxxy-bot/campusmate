  // 固定种子伪随机数：保证每次打开页面生成的课表完全一致，便于答辩复现。
  function mulberry32(seed) {
    let a = seed >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function buildTimetable(rooms) {
    const rand = mulberry32(20260308);
    const weekRanges = [[1, 16], [1, 8], [9, 16], [1, 18], [3, 12]];
    const entries = [];
    let seq = 0;
    rooms.forEach(function (room) {
      for (let day = 1; day <= 5; day += 1) {
        const blocks = [1, 2, 3, 4, 5, 6];
        // Fisher-Yates 洗牌，随机挑选当天占用的两节连堂
        for (let i = blocks.length - 1; i > 0; i -= 1) {
          const j = Math.floor(rand() * (i + 1));
          const tmp = blocks[i];
          blocks[i] = blocks[j];
          blocks[j] = tmp;
        }
        let count = 2 + Math.floor(rand() * 3);
        const dice = rand();
        if (dice < 0.1) count = 0;
        else if (dice < 0.28) count = 1;
        else if (dice > 0.94) count = 6;
        const chosen = blocks.slice(0, count).sort(function (a, b) { return a - b; });
        chosen.forEach(function (block) {
          const course = COURSE_POOL[Math.floor(rand() * COURSE_POOL.length)];
          const weeks = weekRanges[Math.floor(rand() * weekRanges.length)];
          seq += 1;
          entries.push({
            id: 'T' + String(seq).padStart(4, '0'),
            roomId: room.id,
            day: day,
            start: block * 2 - 1,
            end: block * 2,
            course: course.name,
            teacher: course.teacher,
            className: CLASS_NAMES[Math.floor(rand() * CLASS_NAMES.length)],
            weekStart: weeks[0],
            weekEnd: weeks[1]
          });
        });
      }
    });
    return entries;
  }

